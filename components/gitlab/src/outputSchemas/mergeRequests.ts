import { pipelineDetailSchema, pipelineSchema } from "./pipelines";
import {
  bool,
  list,
  nullable,
  nullableBool,
  nullableNum,
  nullableStr,
  num,
  obj,
  referencesSchema,
  str,
  strArray,
  userSchema,
} from "./shared";
export const mergeRequestSchema = obj({
  id: num,
  iid: num,
  project_id: num,
  title: str,
  description: nullableStr,
  state: str,
  draft: bool,
  imported: bool,
  imported_from: nullableStr,
  created_at: str,
  updated_at: str,
  merged_at: nullableStr,
  merge_after: nullableStr,
  prepared_at: nullableStr,
  closed_at: nullableStr,
  closed_by: nullable(userSchema),
  source_branch: str,
  target_branch: str,
  source_project_id: num,
  target_project_id: num,
  labels: strArray,
  author: obj({ ...userSchema.properties, bot: bool }),
  assignees: list(userSchema),
  reviewers: list(userSchema),
  merge_user: nullable(userSchema),
  milestone: nullable(
    obj({
      id: num,
      iid: num,
      project_id: nullableNum,
      group_id: nullableNum,
      title: str,
      description: nullableStr,
      state: str,
      due_date: nullableStr,
      start_date: nullableStr,
      expired: bool,
      created_at: str,
      updated_at: str,
      web_url: str,
    }),
  ),
  detailed_merge_status: str,
  merge_error: nullableStr,
  has_conflicts: bool,
  blocking_discussions_resolved: bool,
  merge_when_pipeline_succeeds: bool,
  should_remove_source_branch: nullableBool,
  force_remove_source_branch: nullableBool,
  allow_collaboration: bool,
  squash: bool,
  squash_on_merge: bool,
  sha: str,
  merge_commit_sha: nullableStr,
  squash_commit_sha: nullableStr,
  discussion_locked: nullableBool,
  upvotes: num,
  downvotes: num,
  user_notes_count: num,
  subscribed: bool,
  changes_count: nullableStr,
  diverged_commits_count: nullableNum,
  rebase_in_progress: bool,
  first_contribution: bool,
  first_deployed_to_production_at: nullableStr,
  latest_build_started_at: nullableStr,
  latest_build_finished_at: nullableStr,
  pipeline: nullable(pipelineSchema),
  head_pipeline: nullable(pipelineDetailSchema),
  diff_refs: nullable(obj({ base_sha: str, head_sha: str, start_sha: str })),
  time_stats: obj({
    time_estimate: num,
    total_time_spent: num,
    human_time_estimate: nullableStr,
    human_total_time_spent: nullableStr,
  }),
  task_completion_status: obj({ count: num, completed_count: num }),
  user: obj({ can_merge: bool }),
  web_url: str,
  references: referencesSchema,
});
export const mergeRequestListSchema = list(mergeRequestSchema);
export const acceptMergeRequestOutputSchema = mergeRequestSchema;
export const createMergeRequestOutputSchema = mergeRequestSchema;
export const getMergeRequestOutputSchema = mergeRequestSchema;
export const listMergeRequestsOutputSchema = mergeRequestListSchema;
export const updateMergeRequestOutputSchema = mergeRequestSchema;
